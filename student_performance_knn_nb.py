import numpy as np, pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

# ---------- 1. SETTINGS ----------
CSV_PATH = "student_data.csv"
TARGET   = "G3"
FEATURES = ["absences", "studytime", "failures", "G1", "G2"]

# ---------- 2. LOAD REAL DATA ----------
df = pd.read_csv(CSV_PATH, sep=None, engine="python")
df = df[FEATURES + [TARGET]].drop_duplicates().dropna(subset=[TARGET])
df["performance"] = pd.qcut(df[TARGET], 3, labels=["Low", "Medium", "High"], duplicates="drop")
X, y = df[FEATURES], df["performance"]
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)

# ---------- 3. PREPROCESS (fit on train only) ----------
med, lo, hi = Xtr.median(), Xtr.quantile(.01), Xtr.quantile(.99)
Xtr = Xtr.fillna(med).clip(lo, hi, axis=1)
Xte = Xte.fillna(med).clip(lo, hi, axis=1)

# ---------- 4. TUNE k (CV on train), use best_k ----------
def knn(k): return Pipeline([("sc", StandardScaler()), ("m", KNeighborsClassifier(k))])
ks = range(1, 26)
cv_k = [cross_val_score(knn(k), Xtr, ytr, cv=5).mean() for k in ks]
best_k = ks[int(np.argmax(cv_k))]
print(f"Best k (by CV): {best_k}")

models = {f"KNN (k={best_k})": knn(best_k),
          "Naive Bayes": Pipeline([("sc", StandardScaler()), ("m", GaussianNB())])}

# ---------- 5. SELECT BY CV, TEST ONCE ----------
cv_res = {n: cross_val_score(m, Xtr, ytr, cv=5).mean() for n, m in models.items()}
best = max(cv_res, key=cv_res.get)
test_res = {}
for name, mdl in models.items():
    mdl.fit(Xtr, ytr); pred = mdl.predict(Xte)
    test_res[name] = accuracy_score(yte, pred)
    print(f"\n=== {name} === CV acc: {cv_res[name]:.3f} | Test acc: {test_res[name]:.3f}")
    print(classification_report(yte, pred))
    print("Confusion matrix:\n", confusion_matrix(yte, pred, labels=["Low", "Medium", "High"]))
print(f"\nBest model (selected by CV): {best}")

# ---------- 6. MENTOR ALERTS + CHARTS ----------
mdl = models[best]
dash = Xte.copy()
dash["Predicted"] = mdl.predict(Xte)
dash["Risk_Prob_%"] = (mdl.predict_proba(Xte)[:, list(mdl.classes_).index("Low")] * 100).round(1)
alerts = dash[dash["Predicted"] == "Low"].sort_values("Risk_Prob_%", ascending=False)
alerts.to_csv("mentor_alerts.csv"); print(f"{len(alerts)} students flagged -> mentor_alerts.csv")

fig, ax = plt.subplots(1, 3, figsize=(15, 4))
ax[0].bar(test_res.keys(), test_res.values(), color=["#3b82f6", "#10b981"]); ax[0].set_title("Test Accuracy")
ax[1].plot(ks, cv_k, marker="o"); ax[1].set_title("KNN: k vs CV Accuracy"); ax[1].set_xlabel("k")
dash["Predicted"].value_counts().plot.pie(ax=ax[2], autopct="%1.0f%%"); ax[2].set_title("Predicted Risk Distribution")
plt.tight_layout(); plt.savefig("mentor_dashboard.png"); plt.show()


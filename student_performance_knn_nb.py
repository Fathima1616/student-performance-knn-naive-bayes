# student_performance_knn_nb.py
import numpy as np, pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

# ---------- 1. LOAD DATA (replace with real LMS export) ----------
# Expected columns: attendance_pct, assignments_submitted_pct, avg_assignment_score,
#                   late_submissions, lms_logins_per_week, semester_gpa
try:
    df = pd.read_csv("lms_records.csv")
except FileNotFoundError:                       # synthetic demo data
    rng = np.random.default_rng(42); n = 500
    att = rng.uniform(40, 100, n)
    sub = np.clip(att + rng.normal(0, 12, n), 20, 100)
    score = np.clip(0.6*sub + rng.normal(25, 10, n), 20, 100)
    late = np.clip(((100 - sub)/10 + rng.normal(0, 1.5, n)).round(), 0, 15)
    login = np.clip(att/10 + rng.normal(0, 2, n), 0, 20)
    gpa = np.clip(0.03*att + 0.025*score - 0.1*late + rng.normal(0, 0.4, n) - 0.5, 0, 10)
    df = pd.DataFrame(dict(attendance_pct=att, assignments_submitted_pct=sub,
                           avg_assignment_score=score, late_submissions=late,
                           lms_logins_per_week=login, semester_gpa=gpa))

# ---------- 2. CLEAN & TRANSFORM ----------
df = df.drop_duplicates().dropna(subset=["semester_gpa"])
df = df.fillna(df.median(numeric_only=True))
for c in df.columns.drop("semester_gpa"):       # cap outliers (1st-99th percentile)
    df[c] = df[c].clip(df[c].quantile(.01), df[c].quantile(.99))

df["performance"] = pd.qcut(df["semester_gpa"], 3, labels=["Low", "Medium", "High"])
X, y = df.drop(columns=["semester_gpa", "performance"]), df["performance"]
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)

# ---------- 3. MODELS ----------
models = {
    "KNN (k=7)":   Pipeline([("sc", StandardScaler()), ("m", KNeighborsClassifier(7))]),
    "Naive Bayes": Pipeline([("sc", StandardScaler()), ("m", GaussianNB())]),
}

# ---------- 4. EVALUATE ----------
results = {}
for name, mdl in models.items():
    cv = cross_val_score(mdl, Xtr, ytr, cv=5).mean()
    mdl.fit(Xtr, ytr); pred = mdl.predict(Xte)
    results[name] = accuracy_score(yte, pred)
    print(f"\n=== {name} === CV acc: {cv:.3f} | Test acc: {results[name]:.3f}")
    print(classification_report(yte, pred))
    print("Confusion matrix:\n", confusion_matrix(yte, pred, labels=["Low","Medium","High"]))

# k-tuning for KNN
ks = range(1, 21)
accs = [cross_val_score(Pipeline([("sc", StandardScaler()),
        ("m", KNeighborsClassifier(k))]), Xtr, ytr, cv=5).mean() for k in ks]
best_k = ks[int(np.argmax(accs))]
print(f"\nBest k for KNN: {best_k}")

# ---------- 5. EARLY-WARNING MENTOR DASHBOARD ----------
best = max(results, key=results.get)
print(f"Best model: {best}")
dash = Xte.copy()
dash["Predicted"] = models[best].predict(Xte)
dash["Risk_Prob_%"] = (models[best].predict_proba(Xte)[:, list(models[best].classes_).index("Low")] * 100).round(1)
alerts = dash[dash["Predicted"] == "Low"].sort_values("Risk_Prob_%", ascending=False)
alerts.to_csv("mentor_alerts.csv"); print(f"\n{len(alerts)} students flagged -> mentor_alerts.csv")

fig, ax = plt.subplots(1, 3, figsize=(15, 4))
ax[0].bar(results.keys(), results.values(), color=["#3b82f6", "#10b981"]); ax[0].set_title("Test Accuracy")
ax[1].plot(ks, accs, marker="o"); ax[1].set_title("KNN: k vs CV Accuracy"); ax[1].set_xlabel("k")
dash["Predicted"].value_counts().plot.pie(ax=ax[2], autopct="%1.0f%%"); ax[2].set_title("Risk Distribution")
plt.tight_layout(); plt.savefig("mentor_dashboard.png"); plt.show()